    std::fs::create_dir_all(root)?;
    write(root, "Добро пожаловать.md", WELCOME)?;
    write(root, "Справка/Возможности Markdown.md", MARKDOWN)?;
    write(root, "Справка/Формулы.md", MATH)?;
