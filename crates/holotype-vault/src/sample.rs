/// Рисует картинку-обложку: мягкий градиент с «боке».
fn draw_banner() -> image::RgbaImage {
    let (w, h) = (1200u32, 340u32);
    let mut img = image::RgbaImage::new(w, h);
    let bubbles = [
        (180.0, 90.0, 140.0, [255.0, 255.0, 255.0], 0.10),
        (420.0, 260.0, 90.0, [255.0, 220.0, 255.0], 0.12),
        (760.0, 70.0, 180.0, [200.0, 240.0, 255.0], 0.10),
        (1020.0, 250.0, 120.0, [255.0, 255.0, 255.0], 0.12),
        (600.0, 180.0, 60.0, [255.0, 255.0, 255.0], 0.16),
        (1120.0, 60.0, 50.0, [255.0, 240.0, 200.0], 0.18),
    ];
    for y in 0..h {
        for x in 0..w {
            let t = x as f32 / w as f32;
            let v = y as f32 / h as f32;
            // Градиент: фиолетовый → розовый → голубой.
            let c0 = [108.0, 84.0, 230.0];
            let c1 = [214.0, 107.0, 196.0];
            let c2 = [56.0, 189.0, 248.0];
            let mut c = [0.0f32; 3];
            for i in 0..3 {
                c[i] = if t < 0.5 {
                    c0[i] + (c1[i] - c0[i]) * (t * 2.0)
                } else {
                    c1[i] + (c2[i] - c1[i]) * ((t - 0.5) * 2.0)
                };
                c[i] *= 0.82 + 0.18 * (1.0 - v);
            }
            for (bx, by, r, col, a) in bubbles {
                let d = ((x as f32 - bx).powi(2) + (y as f32 - by).powi(2)).sqrt();
                let k = ((r - d) / r).clamp(0.0, 1.0).powf(0.6) * a;
                for i in 0..3 {
                    c[i] = c[i] * (1.0 - k) + col[i] * k;
                }
            }
            img.put_pixel(x, y, image::Rgba([c[0] as u8, c[1] as u8, c[2] as u8, 255]));
        }
    }
    img
}
